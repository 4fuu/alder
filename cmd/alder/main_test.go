type failingWriter struct {
	writes int
}

func (w *failingWriter) Write([]byte) (int, error) {
	w.writes++
	return 0, errors.New("injected write failure")
}

func invoke(t *testing.T, root string, args ...string) (int, string, string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := run(args, &stdout, &stderr, root)
	return code, stdout.String(), stderr.String()
}

func sourceFile(t *testing.T, root, text string) {
	t.Helper()
	writeSource(t, root, "src/main.al", text)
}

func writeSource(t *testing.T, root, logical, text string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(logical))
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(text), 0644); err != nil {
		t.Fatal(err)
	}
}

func decodeEnvelope(t *testing.T, text string) envelope {
	t.Helper()
	decoder := json.NewDecoder(strings.NewReader(text))
	var got envelope
	if err := decoder.Decode(&got); err != nil {
		t.Fatalf("decode envelope %q: %v", text, err)
	}
	var extra any
	if err := decoder.Decode(&extra); err != io.EOF {
		t.Fatalf("machine output contains more than one envelope: %q", text)
	}
	return got
}

func TestCheckHumanAndJSON(t *testing.T) {
	root := t.TempDir()
	sourceFile(t, root, "fn main() -> I32 { return 0 }\n")
	code, out, errOut := invoke(t, root, "check", "src/main.al")
	if code != 0 || out != "" || errOut != "" {
		t.Fatalf("code=%d stdout=%q stderr=%q", code, out, errOut)
	}
	code, out, errOut = invoke(t, root, "check", "--format=json", "src/main.al")
	got := decodeEnvelope(t, out)
	if code != exitSuccess || errOut != "" || !got.Success || got.Diagnostics == nil {
		t.Fatalf("code=%d stdout=%q stderr=%q", code, out, errOut)
	}
}

func TestMachineFormatSpellings(t *testing.T) {
	root := t.TempDir()
	sourceFile(t, root, "fn main() -> I32 { return 0 }\n")
	for _, args := range [][]string{
		{"check", "--format=json", "src/main.al"},
		{"check", "--format", "json", "src/main.al"},
		{"check", "-format=json", "src/main.al"},
		{"check", "-format", "json", "src/main.al"},
		{"check", "--format=human", "--format=json", "src/main.al"},
	} {
		code, out, errOut := invoke(t, root, args...)
		got := decodeEnvelope(t, out)
		if code != exitSuccess || errOut != "" || !got.Success {
			t.Fatalf("%v: code=%d stdout=%q stderr=%q", args, code, out, errOut)
		}
	}
}

func TestDiagnosticParityAndNoAbsolutePath(t *testing.T) {
	root := t.TempDir()
	sourceFile(t, root, "fn main() -> I32 { return nope }\n")
	code, human, humanErr := invoke(t, root, "check", "src/main.al")
	if code != 1 || human != "" || !strings.Contains(humanErr, "src/main.al:1:") {
		t.Fatalf("code=%d stdout=%q stderr=%q", code, human, humanErr)
	}
	code, out, errOut := invoke(t, root, "check", "--format=json", "src/main.al")
	got := decodeEnvelope(t, out)
	if code != exitDiagnostics || errOut != "" || len(got.Diagnostics) != 1 {
		t.Fatalf("code=%d stdout=%q stderr=%q", code, out, errOut)
	}
	d := got.Diagnostics[0]
	if !strings.Contains(humanErr, d.Code) || d.Range.Path != "src/main.al" || strings.Contains(out, root) {
		t.Fatalf("human=%q json=%q", humanErr, out)
	}
}

func TestCompileOutputs(t *testing.T) {
	root := t.TempDir()
	sourceFile(t, root, "fn main() -> I32 { return 0 }\n")
	code, out, errOut := invoke(t, root, "compile", "--emit=mir", "src/main.al")
	if code != 0 || errOut != "" || !strings.Contains(out, "mir 6\n") {
		t.Fatalf("code=%d stdout=%q stderr=%q", code, out, errOut)
	}
	code, out, errOut = invoke(t, root, "compile", "--format=json", "--emit=c", "-o", "out.c", "src/main.al")
	got := decodeEnvelope(t, out)
	data, readErr := os.ReadFile(filepath.Join(root, "out.c"))
	if code != exitSuccess || errOut != "" || got.Artifact == nil || got.Artifact.Path != "out.c" || got.Artifact.Content != "" || readErr != nil || !bytes.Contains(data, []byte("Generated by")) {
		t.Fatalf("code=%d stdout=%q stderr=%q read=%v", code, out, errOut, readErr)
	}
}

func TestDiagnosticsAreIndependentOfWorkspaceRoot(t *testing.T) {
	roots := []string{t.TempDir(), t.TempDir()}
	for _, root := range roots {
		sourceFile(t, root, "fn main() -> I32 { return missing }\n")
	}

	for _, args := range [][]string{{"check", "src/main.al"}, {"check", "--format=json", "src/main.al"}} {
		codeA, outA, errA := invoke(t, roots[0], args...)
		codeB, outB, errB := invoke(t, roots[1], args...)
		if codeA != exitDiagnostics || codeB != codeA || outA != outB || errA != errB {
			t.Fatalf("%v differs across roots:\nA=(%d, %q, %q)\nB=(%d, %q, %q)", args, codeA, outA, errA, codeB, outB, errB)
		}
		if strings.Contains(outA, roots[0]) || strings.Contains(outA, roots[1]) || strings.Contains(errA, roots[0]) || strings.Contains(errA, roots[1]) {
			t.Fatalf("%v leaked an absolute workspace path: stdout=%q stderr=%q", args, outA, errA)
		}
	}
}

func TestMultiSourceCLIIsOrderIndependent(t *testing.T) {
	root := t.TempDir()
	writeSource(t, root, "a/helper.al", "fn helper() -> I32 { return 0 }\n")
	writeSource(t, root, "z/main.al", "fn main() -> I32 { return helper() }\n")

	var outputs []string
	for _, inputs := range [][]string{{"z/main.al", "a/helper.al"}, {"a/helper.al", "z/main.al"}} {
		args := append([]string{"compile", "--format=json", "--emit=mir"}, inputs...)
		code, out, errOut := invoke(t, root, args...)
		got := decodeEnvelope(t, out)
		if code != exitSuccess || errOut != "" || got.Artifact == nil || got.Artifact.Kind != "mir" {
			t.Fatalf("inputs=%v code=%d stdout=%q stderr=%q", inputs, code, out, errOut)
		}
		outputs = append(outputs, out)
	}
	if outputs[0] != outputs[1] {
		t.Fatalf("multi-source JSON differs by input order:\n%s\n%s", outputs[0], outputs[1])
	}
}

func TestMultiSourceDuplicateDiagnosticRendersRelatedPath(t *testing.T) {
	root := t.TempDir()
	writeSource(t, root, "a/first.al", "type clash { value: I64 }\n")
	writeSource(t, root, "z/later.al", "fn clash() -> Unit { }\n")

	code, out, errOut := invoke(t, root, "check", "--format=json", "z/later.al", "a/first.al")
	got := decodeEnvelope(t, out)
	if code != exitDiagnostics || errOut != "" || len(got.Diagnostics) != 1 || len(got.Diagnostics[0].Related) != 1 {
		t.Fatalf("code=%d stdout=%q stderr=%q", code, out, errOut)
	}
	diagnostic := got.Diagnostics[0]
	if diagnostic.Range.Path != "z/later.al" || diagnostic.Related[0].Range.Path != "a/first.al" {
		t.Fatalf("unexpected primary/related paths: %+v", diagnostic)
	}
	code, _, human := invoke(t, root, "check", "a/first.al", "z/later.al")
	if code != exitDiagnostics || !strings.Contains(human, "z/later.al:") || !strings.Contains(human, "a/first.al:") {
		t.Fatalf("human duplicate diagnostic missing paths: code=%d stderr=%q", code, human)
	}
}

func TestDiagnosticRenderingUsesSourceIdentity(t *testing.T) {
	source := frontend.Source{ID: 27, Path: "nested/input.al", Text: "éx\n"}
	diagnostic := frontend.Diagnostic{
		Code:     frontend.CodeSemantic,
		Severity: frontend.SeverityError,
		Message:  "failure",
		Primary:  frontend.Span{Source: source.ID, Start: 2, End: 3},
	}
	records, err := adaptDiagnostics(map[frontend.SourceID]frontend.Source{source.ID: source}, []frontend.Diagnostic{diagnostic})
	if err != nil || len(records) != 1 || records[0].Range.Path != source.Path || records[0].Range.Start.Line != 1 || records[0].Range.Start.Column != 2 {
		t.Fatalf("unexpected rendered diagnostic: records=%#v err=%v", records, err)
	}
	diagnostic.Primary.End = len(source.Text) + 1
	if _, err := adaptDiagnostics(map[frontend.SourceID]frontend.Source{source.ID: source}, []frontend.Diagnostic{diagnostic}); err == nil {
		t.Fatal("invalid source range was not rejected as an internal rendering failure")
	}
}

func TestMachineFailuresUseOneEnvelope(t *testing.T) {
	root := t.TempDir()
	for _, test := range []struct {
		name string
		args []string
		code int
		kind string
	}{
		{"usage", []string{"check", "--format=json", "--emit=c", "src/main.al"}, exitUsage, "usage"},
		{"input IO", []string{"check", "--format", "json", "missing.al"}, exitIO, "io"},
	} {
		t.Run(test.name, func(t *testing.T) {
			code, out, errOut := invoke(t, root, test.args...)
			got := decodeEnvelope(t, out)
			if code != test.code || errOut != "" || got.Success || got.Failure == nil || got.Failure.Kind != test.kind {
				t.Fatalf("code=%d stdout=%q stderr=%q envelope=%+v", code, out, errOut, got)
			}
		})
	}
}

func TestWriterFailuresAffectExitStatus(t *testing.T) {
	root := t.TempDir()
	sourceFile(t, root, "fn main() -> I32 { return 0 }\n")

	stdoutFailure := &failingWriter{}
	var stderr bytes.Buffer
	if code := run([]string{"compile", "--emit=mir", "src/main.al"}, stdoutFailure, &stderr, root); code != exitIO || stdoutFailure.writes != 1 {
		t.Fatalf("human artifact writer failure: code=%d writes=%d stderr=%q", code, stdoutFailure.writes, stderr.String())
	}

	machineFailure := &failingWriter{}
	stderr.Reset()
	if code := run([]string{"check", "--format=json", "src/main.al"}, machineFailure, &stderr, root); code != exitIO || machineFailure.writes != 1 || stderr.Len() != 0 {
		t.Fatalf("machine writer failure: code=%d writes=%d stderr=%q", code, machineFailure.writes, stderr.String())
	}

	sourceFile(t, root, "fn main() -> I32 { return missing }\n")
	stderrFailure := &failingWriter{}
	if code := run([]string{"check", "src/main.al"}, io.Discard, stderrFailure, root); code != exitIO || stderrFailure.writes != 1 {
		t.Fatalf("human diagnostic writer failure: code=%d writes=%d", code, stderrFailure.writes)
	}
}

func TestAtomicOutputReplacesFilesAndPreservesOtherTargetsOnFailure(t *testing.T) {
	root := t.TempDir()
	sourceFile(t, root, "fn main() -> I32 { return 0 }\n")
	output := filepath.Join(root, "out.c")
	if err := os.WriteFile(output, []byte("old content"), 0644); err != nil {
		t.Fatal(err)
	}
	code, out, errOut := invoke(t, root, "compile", "--emit=c", "-o", "out.c", "src/main.al")
	data, err := os.ReadFile(output)
	if code != exitSuccess || out != "" || errOut != "" || err != nil || bytes.Equal(data, []byte("old content")) || !bytes.Contains(data, []byte("Generated by")) {
		t.Fatalf("replace: code=%d stdout=%q stderr=%q data=%q err=%v", code, out, errOut, data, err)
	}

	blocked := filepath.Join(root, "blocked")
	if err := os.Mkdir(blocked, 0755); err != nil {
		t.Fatal(err)
	}
	code, _, _ = invoke(t, root, "compile", "--emit=c", "-o", "blocked", "src/main.al")
	info, statErr := os.Stat(blocked)
	temps, globErr := filepath.Glob(filepath.Join(root, ".alder-*"))
	if code != exitIO || statErr != nil || !info.IsDir() || globErr != nil || len(temps) != 0 {
		t.Fatalf("failed replace changed target or leaked temp: code=%d info=%v stat=%v temps=%v glob=%v", code, info, statErr, temps, globErr)
	}
}

