package compiler

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// A `using` registration records the owner's local place, not the value at
// registration. A `mut self` method may therefore change the owner after the
// registration, and the cleanup hook observes the value the binding holds at
// scope exit. This fixture mutates a `let`-bound owner after registering it;
// the counter receives 5, while the registration-time capture would report 0.
const m8CleanupPlaceProgram = `import c counter: fn(U64) -> Unit
type Boxed {
    n: U64
}
impl Boxed {
    fn poke(mut self, v: U64) -> Unit {
        self.n = v
    }
}
impl Cleanup for Boxed {
    fn cleanup(take self) -> Unit {
        unsafe c { counter(self.n) }
        return
    }
}
fn main() -> I32 {
    using held = Boxed(n: 0)
    held.poke(5)
    return 0
}
`

func TestM8CleanupObservesCurrentOwner(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	files := map[string]string{"cleanup-place.al": m8CleanupPlaceProgram}
	mirText := runPrivateProductionCompiler(t, exe, files, "compile", "--emit=mir", "cleanup-place.al")
	if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
		t.Fatalf("MIR result: %+v stderr=%s", mirText, mirText.stderr)
	}
	if !strings.Contains(mirText.stdout, "cleanup.push") || !strings.Contains(mirText.stdout, "place local") {
		t.Fatalf("cleanup registration does not name the owner place:\n%s", mirText.stdout)
	}
	cResult := runPrivateProductionCompiler(t, exe, files, "compile", "--emit=c", "cleanup-place.al")
	if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
		t.Fatalf("C result: %+v stderr=%s", cResult, cResult.stderr)
	}
	compileAndRunProductionArtifactWithDriver(t, cc, root, runtimeObject, cResult.stdout, m75UsingLoopDriver(5), 0)
}
