// M7.5 affine Vec elements: Vec(T) over a Cleanup owner drains every element
// at scope exit through callback-free using. The programs compile and run end
// to end through the Alder production driver on generated C; they avoid every
// private bootstrap name. They intentionally stay out of the Go-frontend
// oracle corpora: the Go checker has neither trait implementations nor the
// drain surface.

const m75VecDrainProgram = `import c counter: fn(U64) -> Unit
type Res {
    n: U64
}
impl Cleanup for Res {
    fn cleanup(take self) -> Unit {
        unsafe c { counter(self.n) }
        return
    }
}
fn make(n: U64) -> Res { return Res(n: n) }
fn early(flag: Bool) -> I32 {
    let v = Vec.new(Res)
    v.push(make(10))
    v.push(make(20))
    using w = v
    if flag { return 5 }
    return 0
}
fn recv(take v: Vec(Res)) -> I32 {
    using local = v
    if local.len() != 1 { return 7 }
    return 0
}
fn main() -> I32 {
    if early(true) != 5 { return 91 }
    if early(false) != 0 { return 92 }
    let u = Vec.new(Res)
    u.push(make(50))
    recv(u)
    let empty = Vec.new(Res)
    using drained = empty
    return 0
}
`

var m75VecRejections = []struct {
	name, source, want string
}{
	{
		"element-access",
		"type Res { n: U64 }\nimpl Cleanup for Res {\n    fn cleanup(take self) -> Unit { return }\n}\nfn f() -> Unit {\n    let v = Vec.new(Res)\n    let one = v.get(0)\n}\nfn main() -> I32 { return 0 }\n",
		"a Vec of affine elements supports push and len only",
	},
	{
		"push-after-registration",
		"type Res { n: U64 }\nimpl Cleanup for Res {\n    fn cleanup(take self) -> Unit { return }\n}\nfn f() -> Unit {\n    using w = Vec.new(Res)\n    w.push(Res(n: 1))\n}\nfn main() -> I32 { return 0 }\n",
		"a registered vector owner is immutable",
	},
	{
		"table-element",
		"fn f() -> Unit { let v = Vec.new(Table(U64)) }\nfn main() -> I32 { return 0 }\n",
		"a Table cannot be a Vec element yet",
	},
}

func TestM75VecProductionQualification(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	files := map[string]string{"m75-vec-drain.al": m75VecDrainProgram}
	mirText := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "m75-vec-drain.al")
	if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 5\n") {
		t.Fatalf("vec drain MIR result: %+v stderr=%s", mirText, mirText.stderr)
	}
	repeat := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "m75-vec-drain.al")
	if repeat != mirText {
		t.Fatal("vec drain MIR changed across processes")
	}
	cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", "m75-vec-drain.al")
	if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
		t.Fatalf("vec drain C result: %+v stderr=%s", cResult, cResult.stderr)
	}
	if strings.Contains(cResult.stdout, "__s0_") {
		t.Fatal("vec drain generated C exposes bootstrap names")
	}
	// Every push drains exactly once per element on every exit path: the
	// early return and normal return of early(), the take-param registration
	// of recv(), and the empty registration observe 10+20+10+20+50 = 110
	// across five cleanup calls.
	const counterDriver = `#include "alder_host.h"
#include <stdint.h>
static uint64_t g_count = 0;
static uint64_t g_sum = 0;
void counter(uint64_t v) { g_count++; g_sum += v; }
int main(void) {
	int context = 0;
	int result = (int)alder_program_entry(&context);
	if (g_count != 5) { return 97; }
	if (g_sum != 110) { return 98; }
	return result;
}
`
	compileAndRunProductionArtifactWithDriver(t, cc, root, runtimeObject, cResult.stdout, counterDriver, 0)

	for _, rejection := range m75VecRejections {
		rejection := rejection
		t.Run("reject-"+rejection.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{"reject.al": rejection.source}
			result := runProductionCompiler(t, exe, files, "check", "reject.al")
			if result.status == 0 || !strings.Contains(result.stderr, rejection.want) {
				t.Fatalf("reject %s: status=%d stderr=%q", rejection.name, result.status, result.stderr)
			}
		})
	}
}
