// D023: a mutating collection operation updates its target in place when the
// compiler proves the source storage uniquely owned, and every remaining
// value-semantics copy site is reported with its reason through
// --report-copies. These programs pin observable behavior: an aliased source
// still copies, a dead source moves, and parameter storage never moves
// inside the callee.

const d023AliasProgram = `fn main() -> I32 {
    var a = Vec.new(U64)
    a.push(1)
    var b = a
    b.push(2)
    if a.len() != 1 { return 1 }
    if b.len() != 2 { return 2 }
    return 0
}
`

const d023DeadSourceProgram = `fn main() -> I32 {
    var a = Vec.new(U64)
    a.push(1)
    var b = a
    b.push(2)
    if b.len() != 2 { return 1 }
    return 0
}
`

const d023ParameterProgram = `fn value_at(v: Vec(U64), i: U64) -> U64 {
    return match v.get(i) {
        Some(x) => x
        None => 999
    }
}
fn push_one(a: Vec(U64)) -> Vec(U64) {
    var b = a
    b.push(1)
    return b
}
fn main() -> I32 {
    var a = Vec.new(U64)
    a.push(5)
    let r = push_one(a)
    a.push(9)
    if r.len() != 2 { return 1 }
    if a.len() != 2 { return 2 }
    if value_at(a, 1) != 9 { return 3 }
    if value_at(r, 0) != 5 { return 4 }
    return 0
}
`

const d023DeadArgumentProgram = `fn value_at(v: Vec(U64), i: U64) -> U64 {
    return match v.get(i) {
        Some(x) => x
        None => 999
    }
}
fn push_one(a: Vec(U64)) -> Vec(U64) {
    var b = a
    b.push(1)
    return b
}
fn main() -> I32 {
    var a = Vec.new(U64)
    a.push(5)
    let r = push_one(a)
    if r.len() != 2 { return 1 }
    if value_at(r, 0) != 5 { return 2 }
    return 0
}
`

const d023EscapedTargetProgram = `fn make() -> Vec(U64) {
    var a = Vec.new(U64)
    a.push(3)
    let b = a
    return b
}
fn main() -> I32 {
    let r = make()
    if r.len() != 1 { return 1 }
    return 0
}
`

const d023LoopRebuildProgram = `fn rebuild(src: Vec(U64)) -> Vec(U64) {
    var out = Vec.new(U64)
    var i: U64 = 0
    while i < src.len() {
        match src.get(i) {
            Some(x) => { out.push(x) }
            None => { }
        }
        i = i + 1
    }
    out.push(src.len())
    return out
}
fn main() -> I32 {
    var a = Vec.new(U64)
    a.push(5)
    var i: U64 = 0
    while i < 3 {
        a = rebuild(a)
        i = i + 1
    }
    if a.len() != 4 { return 1 }
    var total: U64 = 0
    var j: U64 = 0
    while j < a.len() {
        match a.get(j) {
            Some(x) => { total = total + x }
            None => { }
        }
        j = j + 1
    }
    if total != 11 { return 2 }
    return 0
}
`

const d023LoopRereadProgram = `fn add_one(v: Vec(U64)) -> Vec(U64) {
    var b = v
    b.push(1)
    return b
}
fn main() -> I32 {
    var a = Vec.new(U64)
    a.push(5)
    var total: U64 = 0
    var i: U64 = 0
    while i < 3 {
        let b = add_one(a)
        total = total + b.len()
        i = i + 1
    }
    if total != 6 { return 1 }
    return 0
}
`

const d023PerSiteReasonProgram = `fn add_one(v: Vec(U64)) -> Vec(U64) {
    var b = v
    b.push(1)
    return b
}
fn main() -> I32 {
    var a = Vec.new(U64)
    a.push(5)
    var total: U64 = 0
    var i: U64 = 0
    while i < 2 {
        let b = add_one(a)
        total = total + b.len()
        i = i + 1
    }
    let c = add_one(a)
    let d = add_one(a)
    if total != 4 { return 1 }
    if c.len() != 2 { return 2 }
    if d.len() != 2 { return 3 }
    return 0
}
`

func TestM75D023ProductionQualification(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	programs := []struct {
		name, text string
	}{
		{"d023-alias.al", d023AliasProgram},
		{"d023-dead-source.al", d023DeadSourceProgram},
		{"d023-parameter.al", d023ParameterProgram},
		{"d023-dead-argument.al", d023DeadArgumentProgram},
		{"d023-escaped-target.al", d023EscapedTargetProgram},
		{"d023-loop-rebuild.al", d023LoopRebuildProgram},
		{"d023-loop-reread.al", d023LoopRereadProgram},
		{"d023-per-site-reason.al", d023PerSiteReasonProgram},
	}
	for _, program := range programs {
		program := program
		t.Run(program.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{program.name: program.text}
			cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", program.name)
			if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
				t.Fatalf("%s C result: %+v stderr=%s", program.name, cResult, cResult.stderr)
			}
			compileAndRunProductionArtifact(t, cc, root, runtimeObject, cResult.stdout, 0)
		})
	}

	// The alias program must keep its copy and report it with the reason.
	aliasReport := runProductionCompiler(t, exe, map[string]string{"d023-alias.al": d023AliasProgram}, "check", "--report-copies", "d023-alias.al")
	if aliasReport.status != 0 {
		t.Fatalf("alias report run: %+v stderr=%s", aliasReport, aliasReport.stderr)
	}
	report := aliasReport.stdout + aliasReport.stderr
	if !strings.Contains(report, "copy of `a`") || !strings.Contains(report, "still used later") {
		t.Fatalf("alias report missing the remaining copy site: %q", report)
	}

	// The dead-source program moves: no copy call remains in its C.
	deadC := runProductionCompiler(t, exe, map[string]string{"d023-dead-source.al": d023DeadSourceProgram}, "compile", "--emit=c", "d023-dead-source.al")
	if deadC.status != 0 || strings.Contains(deadC.stdout, "= alder_copy_ty") {
		t.Fatalf("dead-source program still copies: status=%d", deadC.status)
	}
	deadReport := runProductionCompiler(t, exe, map[string]string{"d023-dead-source.al": d023DeadSourceProgram}, "check", "--report-copies", "d023-dead-source.al")
	if deadReport.status != 0 {
		t.Fatalf("dead-source report run: %+v", deadReport)
	}
	if strings.Contains(deadReport.stdout+deadReport.stderr, "still used later") {
		t.Fatalf("dead-source report should be empty: %q", deadReport.stdout+deadReport.stderr)
	}

	// Parameter storage never moves inside the callee, and the caller's
	// live argument still copies; the dead argument does not.
	paramReport := runProductionCompiler(t, exe, map[string]string{"d023-parameter.al": d023ParameterProgram}, "check", "--report-copies", "d023-parameter.al")
	if paramReport.status != 0 {
		t.Fatalf("parameter report run: %+v", paramReport)
	}
	paramText := paramReport.stdout + paramReport.stderr
	if !strings.Contains(paramText, "parameter storage shared with the caller") || !strings.Contains(paramText, "still used later") {
		t.Fatalf("parameter report missing its two reasons: %q", paramText)
	}
	deadArgReport := runProductionCompiler(t, exe, map[string]string{"d023-dead-argument.al": d023DeadArgumentProgram}, "check", "--report-copies", "d023-dead-argument.al")
	if deadArgReport.status != 0 {
		t.Fatalf("dead-argument report run: %+v", deadArgReport)
	}
	deadArgText := deadArgReport.stdout + deadArgReport.stderr
	if strings.Contains(deadArgText, "still used later") {
		t.Fatalf("dead argument should not report a later use: %q", deadArgText)
	}
	if !strings.Contains(deadArgText, "parameter storage shared with the caller") {
		t.Fatalf("dead-argument report missing the callee parameter copy: %q", deadArgText)
	}
	// A loop that rebuilds the binding moves: the loop-rebuild shape
	// `a = rebuild(a)` re-establishes `a` from the call result before the read
	// repeats, so the argument transfers instead of copying. The program
	// checks the rebuilt contents, so a move that corrupted the source would
	// return a wrong status rather than merely cost a copy.
	rebuildC := runProductionCompiler(t, exe, map[string]string{"d023-loop-rebuild.al": d023LoopRebuildProgram}, "compile", "--emit=c", "d023-loop-rebuild.al")
	if rebuildC.status != 0 {
		t.Fatalf("loop-rebuild C run: %+v stderr=%s", rebuildC, rebuildC.stderr)
	}
	// The one remaining copy call is the callee's return-value copy, which no
	// move can remove; the loop site itself contributes none.
	if got := strings.Count(rebuildC.stdout, "= alder_copy_ty"); got != 1 {
		t.Fatalf("loop-rebuild program should copy only the callee return, got %d copy calls", got)
	}
	rebuildReport := runProductionCompiler(t, exe, map[string]string{"d023-loop-rebuild.al": d023LoopRebuildProgram}, "check", "--report-copies", "d023-loop-rebuild.al")
	if rebuildReport.status != 0 {
		t.Fatalf("loop-rebuild report run: %+v", rebuildReport)
	}
	if got := rebuildReport.stdout + rebuildReport.stderr; got != "" {
		t.Fatalf("loop-rebuild report should be empty, got %q", got)
	}

	// The boundary: a body that only reads the binding never re-establishes
	// it, so the next iteration would read storage the callee owns. That site
	// keeps its copy and reports the loop reason.
	rereadC := runProductionCompiler(t, exe, map[string]string{"d023-loop-reread.al": d023LoopRereadProgram}, "compile", "--emit=c", "d023-loop-reread.al")
	if rereadC.status != 0 {
		t.Fatalf("loop-reread C run: %+v stderr=%s", rereadC, rereadC.stderr)
	}
	// Two copies are the callee's own (its parameter and its return value);
	// the third is the loop site, which cannot move here.
	if got := strings.Count(rereadC.stdout, "= alder_copy_ty"); got != 3 {
		t.Fatalf("loop-reread program should keep its loop-site copy, got %d copy calls", got)
	}
	rereadReport := runProductionCompiler(t, exe, map[string]string{"d023-loop-reread.al": d023LoopRereadProgram}, "check", "--report-copies", "d023-loop-reread.al")
	if rereadReport.status != 0 {
		t.Fatalf("loop-reread report run: %+v", rereadReport)
	}
	if rereadText := rereadReport.stdout + rereadReport.stderr; !strings.Contains(rereadText, "copy of `a`: re-read by a loop") {
		t.Fatalf("loop-reread report missing the loop reason: %q", rereadText)
	}
	// One binding can have a read that copies and a later read that moves.
	// Each remaining copy site is reported with its own reason: the loop body
	// never re-establishes `a`, so that site copies for the loop reason, the
	// next read copies because the read after it still uses `a`, and the last
	// read moves and is not reported at all.
	perSiteReport := runProductionCompiler(t, exe, map[string]string{"d023-per-site-reason.al": d023PerSiteReasonProgram}, "check", "--report-copies", "d023-per-site-reason.al")
	if perSiteReport.status != 0 {
		t.Fatalf("per-site report run: %+v", perSiteReport)
	}
	perSiteText := perSiteReport.stdout + perSiteReport.stderr
	if !strings.Contains(perSiteText, "copy of `a`: re-read by a loop") || !strings.Contains(perSiteText, "copy of `a`: still used later") {
		t.Fatalf("per-site report should name both sites with their own reasons: %q", perSiteText)
	}
	if got := strings.Count(perSiteText, "copy of `a`"); got != 2 {
		t.Fatalf("per-site report should name exactly the two copying reads, got %d: %q", got, perSiteText)
	}
}
