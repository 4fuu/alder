// Interpolation is source sugar over Display and String.concat. The program
// exercises the builtin domain, a user Display implementation, literal brace
// escapes and bare right braces, and left-to-right evaluation of the embedded
// expressions.
const interpolationProgram = `type User {
    name: String
    age: U64
}

impl Display for User {
    fn display(self) -> String {
        return self.name
    }
}

type Counter {
    value: U64
}

impl Counter {
    fn bump(mut self) -> U64 {
        self.value = self.value + 1
        return self.value
    }
}

fn main() -> I32 {
    let user = User(name: "Ada", age: 36)
    let person: String = "{user.name}: {user.age}"
    if person.len() != 7 { return 1 }
    if person.byte(0) != 65 { return 2 }
    if person.byte(3) != 58 { return 3 }
    if person.byte(6) != 54 { return 4 }
    let shown: String = "<{user}>"
    if shown.len() != 5 { return 5 }
    if shown.byte(1) != 65 { return 6 }
    let braces: String = "\{literal\} and }"
    if braces.len() != 15 { return 7 }
    if braces.byte(0) != 123 { return 8 }
    if braces.byte(14) != 125 { return 9 }
    let truth: Bool = true
    let flag: String = "{truth}"
    if flag.len() != 4 { return 10 }
    if flag.byte(0) != 116 { return 11 }
    var counter = Counter(value: 0)
    let order: String = "{counter.bump()}-{counter.bump()}"
    if order.len() != 3 { return 12 }
    if order.byte(0) != 49 { return 13 }
    if order.byte(2) != 50 { return 14 }
    return 0
}
`

var interpolationRejections = []struct {
	name string
	src  string
	want string
}{
	{
		name: "float-part",
		src:  "fn main() -> I32 {\n    let value: F64 = 1.5\n    let text: String = \"{value}\"\n    return 0\n}\n",
		want: "does not implement Display",
	},
	{
		name: "empty",
		src:  "fn main() -> I32 {\n    let text: String = \"{}\"\n    return 0\n}\n",
		want: "interpolation expressions are brace-free",
	},
	{
		name: "match-expression",
		src:  "fn main() -> I32 {\n    let value = 1\n    let text: String = \"{match value { 1 => 2 }}\"\n    return 0\n}\n",
		want: "interpolation expressions are brace-free",
	},
	{
		name: "unterminated",
		src:  "fn main() -> I32 {\n    let value = 1\n    let text: String = \"{value",
		want: "expected `}` to close interpolation",
	},
}

func TestInterpolationProductionQualification(t *testing.T) {
	t.Parallel()
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	files := map[string]string{"interpolation.al": interpolationProgram}
	mirText := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "interpolation.al")
	if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
		t.Fatalf("interpolation MIR result: %+v stderr=%s", mirText, mirText.stderr)
	}
	repeat := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "interpolation.al")
	if repeat != mirText {
		t.Fatal("interpolation MIR changed across processes")
	}
	cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", "interpolation.al")
	if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
		t.Fatalf("interpolation C result: %+v stderr=%s", cResult, cResult.stderr)
	}
	compileAndRunProductionArtifact(t, cc, root, runtimeObject, cResult.stdout, 0)

	for _, rejection := range interpolationRejections {
		rejection := rejection
		t.Run("reject-"+rejection.name, func(t *testing.T) {
			t.Parallel()
			result := runProductionCompiler(t, exe, map[string]string{"reject.al": rejection.src}, "check", "reject.al")
			if result.status == 0 {
				t.Fatalf("reject %s accepted: %+v", rejection.name, result)
			}
			if !strings.Contains(result.stderr, rejection.want) {
				t.Fatalf("reject %s diagnostic: got %q, want %q", rejection.name, result.stderr, rejection.want)
			}
		})
	}
}
