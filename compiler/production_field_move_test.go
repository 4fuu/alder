// A `take self` method may move its record fields out one at a time. The
// wrapper's own Cleanup hook does not run for the taken binding (the caller
// disarmed it before entry), so every remaining affine field must itself be
// moved or registered. The counter proves the returned sink is released
// exactly once by the caller's registration.
const m8FieldMoveProgram = `import c counter: fn(U64) -> Unit
type Sink {
    n: U64
}
impl Cleanup for Sink {
    fn cleanup(take self) -> Unit {
        unsafe c { counter(self.n) }
        return
    }
}
type Bag {
    sink: Sink
    buffer: Vec(U8)
}
impl Bag {
    fn into_sink(take self) -> Sink {
        return self.sink
    }
}
fn main() -> I32 {
    let bag = Bag(sink: Sink(n: 7), buffer: Vec.new(U8))
    using kept = bag.into_sink()
    if kept.n != 7 { return 1 }
    return 0
}
`

var m8FieldMoveRejections = []struct {
	name, source, want string
}{
	{
		// Moving one affine field leaves the other live: the taken binding's
		// flow is satisfied only when every affine field is moved out.
		"second-affine-field-live",
		`type Sink {
    n: U64
}
impl Cleanup for Sink {
    fn cleanup(take self) -> Unit { return }
}
type Pair {
    a: Sink
    b: Sink
}
impl Pair {
    fn take_a(take self) -> Sink {
        return self.a
    }
}
fn main() -> I32 { return 0 }
`,
		"affine owner reaches function exit without an ownership transfer",
	},
	{
		// A field is a sub-owner: after moving it, reading it again is a use
		// after transfer.
		"use-after-field-move",
		`type Sink {
    n: U64
}
impl Cleanup for Sink {
    fn cleanup(take self) -> Unit { return }
}
type Pair {
    a: Sink
    b: Sink
}
impl Pair {
    fn take_both(take self) -> Sink {
        let first = self.a
        let again = self.a
        return first
    }
}
fn main() -> I32 { return 0 }
`,
		"owner was already transferred",
	},
	{
		// A borrowed receiver does not own its fields, so a field may not move
		// out of it.
		"borrowed-receiver-field-move",
		`type Sink {
    n: U64
}
impl Cleanup for Sink {
    fn cleanup(take self) -> Unit { return }
}
type W {
    sink: Sink
}
impl W {
    fn peek(mut self) -> Sink {
        return self.sink
    }
}
fn main() -> I32 { return 0 }
`,
		"cannot move an affine field out of a borrowed owner",
	},
}

func TestM8ConsumedFieldMoves(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	t.Run("moved-field-released-once", func(t *testing.T) {
		t.Parallel()
		files := map[string]string{"field-move.al": m8FieldMoveProgram}
		cResult := runPrivateProductionCompiler(t, exe, files, "compile", "--emit=c", "field-move.al")
		if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
			t.Fatalf("C result: %+v stderr=%s", cResult, cResult.stderr)
		}
		compileAndRunProductionArtifactWithDriver(t, cc, root, runtimeObject, cResult.stdout, m75UsingLoopDriver(7), 0)
	})

	for _, rejection := range m8FieldMoveRejections {
		rejection := rejection
		t.Run("reject-"+rejection.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{"reject.al": rejection.source}
			result := runPrivateProductionCompiler(t, exe, files, "check", "reject.al")
			if result.status == 0 || !strings.Contains(result.stderr, rejection.want) {
				t.Fatalf("reject %s: status=%d stderr=%q", rejection.name, result.status, result.stderr)
			}
		})
	}
}
