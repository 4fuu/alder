package compiler

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// A Cleanup implementation observes every release through an imported C
// counter. The first owner is registered by `using` and then transferred
// into a `take` parameter and returned; the receiving registration owns the
// single release. Exactly one disarm is emitted for the transfer, so the
// counter totals 16 (7 + 9). Without the transfer disarm the exiting scope
// also releases the moved owner and the counter reaches 23, which is the
// regression this fixture guards.
const usingDisarmProgram = `import c counter: fn(U64) -> Unit
type Res {
    n: U64
}
impl Cleanup for Res {
    fn cleanup(take self) -> Unit {
        unsafe c { counter(self.n) }
        return
    }
}
fn make(n: U64) -> Res { return Res(n: n) }
fn relay(take r: Res) -> Res { return r }
fn main() -> I32 {
    using r = make(7)
    using back = relay(r)
    if back.n != 7 { return 2 }
    using late = make(9)
    if late.n != 9 { return 1 }
    return 0
}
`

const usingDisarmDriver = `#include "alder_host.h"
#include <stdint.h>
static uint64_t g_count = 0;
void counter(uint64_t v) { g_count += v; }
int main(void) {
    int context = 0;
    int result = (int)alder_program_entry(&context);
    if (g_count != 16) { return 98; }
    return result;
}
`

// TestUsingDisarmOnTransfer pins the general resource rule independently of
// the C-string surface: a `using`-registered owner that is transferred out of
// its scope disarms that registration, so the receiver's cleanup runs once
// and the exiting scope releases nothing. The check is behavioral through the
// imported counter and structural through the single `cleanup.disarm` in the
// printed MIR and generated C.
func TestUsingDisarmOnTransfer(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	files := map[string]string{"using-disarm.al": usingDisarmProgram}
	check := runPrivateProductionCompiler(t, exe, files, "check", "using-disarm.al")
	if check.status != 0 || check.stderr != "" {
		t.Fatalf("using-disarm check result: %+v stderr=%s", check, check.stderr)
	}
	mirText := runPrivateProductionCompiler(t, exe, files, "compile", "--emit=mir", "using-disarm.al")
	if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
		t.Fatalf("MIR result: %+v stderr=%s", mirText, mirText.stderr)
	}
	if got := strings.Count(mirText.stdout, "cleanup.disarm"); got != 1 {
		t.Fatalf("printed MIR carries %d cleanup disarms, want 1", got)
	}
	cResult := runPrivateProductionCompiler(t, exe, files, "compile", "--emit=c", "using-disarm.al")
	if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
		t.Fatalf("C result: %+v stderr=%s", cResult, cResult.stderr)
	}
	if got := strings.Count(cResult.stdout, "alder_cleanup_disarm("); got != 1 {
		t.Fatalf("generated C carries %d cleanup disarms, want 1", got)
	}
	compileAndRunProductionArtifactWithDriver(t, cc, root, runtimeObject, cResult.stdout, usingDisarmDriver, 0)
}
