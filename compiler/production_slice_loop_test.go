// M8 slice loops: a plain `while` loop that indexes a Slice or MutSlice local
// must verify. The view header is a borrow of the array local, so the loop
// view-read rule has to walk through the borrow to the storage it names; the
// loop neither grows nor stores that storage, so the read is legal.

const m8SliceLoopProgram = `fn first_nonzero(values: [U8], n: U64) -> U8 {
    var found: U8 = 0
    var i: U64 = 0
    while i < n {
        if found == 0 { found = values[i] }
        i = i + 1
    }
    return found
}

fn fill(n: U64, value: U8, mut out: MutSlice(U8)) -> Unit {
    var i: U64 = 0
    while i < n {
        out[i] = value
        i = i + 1
    }
    return
}

fn main() -> I32 {
    var source: Array(U8, 3) = [0, 7, 0]
    let read_view: [U8] = source.slice(0, 3)
    if first_nonzero(read_view, 3) != 7 { return 1 }
    var data: Array(U8, 4) = [0, 0, 0, 0]
    var view: MutSlice(U8) = data.slice_mut(0, 4)
    fill(4, 9, view)
    var i: U64 = 0
    while i < 4 {
        if view[i] != 9 { return 2 }
        i = i + 1
    }
    return 0
}
`

func TestM8SliceLoopIndexing(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	files := map[string]string{"slice-loop.al": m8SliceLoopProgram}
	mirText := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "slice-loop.al")
	if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
		t.Fatalf("MIR result: %+v stderr=%s", mirText, mirText.stderr)
	}
	cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", "slice-loop.al")
	if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
		t.Fatalf("C result: %+v stderr=%s", cResult, cResult.stderr)
	}
	compileAndRunProductionArtifact(t, cc, root, runtimeObject, cResult.stdout, 0)
}
