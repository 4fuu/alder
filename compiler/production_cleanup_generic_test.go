// M8 conditional Cleanup registration: a generic implementation of Cleanup is
// conditional, so `using` records the concrete instance of its `cleanup` hook
// rather than the generic declaration, which owns no MIR body. The counter
// program proves the registered instance runs exactly once and receives the
// registered owner; the constrained program proves the implementation's own
// trait constraints are checked against the owner's concrete type when the
// instance is instantiated.

const m8GenericCleanupProgram = `import c counter: fn(U64) -> Unit
type Boxed(T: type) {
    tag: U64
    v: T
}
impl(T: type) Cleanup for Boxed(T) {
    fn cleanup(take self) -> Unit {
        unsafe c { counter(self.tag * 10 + 1) }
        return
    }
}
fn main() -> I32 {
    let b = Boxed(tag: 4, v: 5)
    using held = b
    if held.v != 5 { return 1 }
    return 0
}
`

const m8ConstrainedCleanupProgram = `trait Marker {
    fn mark(self) -> U64
}
type Mode {
    code: U64
}
impl Marker for Mode {
    fn mark(self) -> U64 {
        return self.code
    }
}
type Boxed(T: type) {
    v: T
}
impl(T: type(Marker)) Cleanup for Boxed(T) {
    fn cleanup(take self) -> Unit {
        return
    }
}
fn main() -> I32 {
    let b = Boxed(v: Mode(code: 1))
    using held = b
    if held.v.mark() != 1 { return 1 }
    return 0
}
`

var m8GenericCleanupRejections = []struct {
	name, source, want string
}{
	{
		// The registration instantiates the conditional implementation for
		// I64, which has no Marker implementation, so the impl's own
		// constraint fails at the using site instead of producing an
		// internal lowering failure.
		"unsatisfied-impl-constraint",
		`trait Marker {
    fn mark(self) -> U64
}
type Boxed(T: type) {
    v: T
}
impl(T: type(Marker)) Cleanup for Boxed(T) {
    fn cleanup(take self) -> Unit {
        return
    }
}
fn main() -> I32 {
    let b = Boxed(v: 5)
    using held = b
    return 0
}
`,
		"type does not implement a trait required here",
	},
}

func TestM8GenericCleanupQualification(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	t.Run("conditional-instance-runs", func(t *testing.T) {
		t.Parallel()
		files := map[string]string{"cleanup-generic.al": m8GenericCleanupProgram}
		mirText := runPrivateProductionCompiler(t, exe, files, "compile", "--emit=mir", "cleanup-generic.al")
		if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
			t.Fatalf("MIR result: %+v stderr=%s", mirText, mirText.stderr)
		}
		if !strings.Contains(mirText.stdout, "cleanup.push") {
			t.Fatalf("MIR has no cleanup registration:\n%s", mirText.stdout)
		}
		cResult := runPrivateProductionCompiler(t, exe, files, "compile", "--emit=c", "cleanup-generic.al")
		if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
			t.Fatalf("C result: %+v stderr=%s", cResult, cResult.stderr)
		}
		// One run of the instance hook counts tag 4 as 41; a missing or
		// duplicated hook run changes the total.
		compileAndRunProductionArtifactWithDriver(t, cc, root, runtimeObject, cResult.stdout, m75UsingLoopDriver(41), 0)
	})

	t.Run("constrained-instance-checks-arguments", func(t *testing.T) {
		t.Parallel()
		files := map[string]string{"cleanup-constrained.al": m8ConstrainedCleanupProgram}
		cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", "cleanup-constrained.al")
		if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
			t.Fatalf("C result: %+v stderr=%s", cResult, cResult.stderr)
		}
		compileAndRunProductionArtifact(t, cc, root, runtimeObject, cResult.stdout, 0)
	})

	for _, rejection := range m8GenericCleanupRejections {
		rejection := rejection
		t.Run("reject-"+rejection.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{"reject.al": rejection.source}
			result := runProductionCompiler(t, exe, files, "check", "reject.al")
			if result.status == 0 || !strings.Contains(result.stderr, rejection.want) {
				t.Fatalf("reject %s: status=%d stderr=%q", rejection.name, result.status, result.stderr)
			}
		})
	}
}
