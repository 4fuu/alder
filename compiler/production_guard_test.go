// D018 match guards qualified through the production driver: guards evaluate
// after the pattern matches, false guards continue with the next arm, and the
// guarded surface compiles to deterministic MIR and strict C11 end to end.

const m75GuardProgram = `fn route(code: U64, flag: Bool) -> U64 {
    let wrapped: Result(U64, U64) = Ok(code)
    return match wrapped {
        Ok(v) if flag && v > 900 => 1
        Ok(v) if v > 100 => 2
        Ok(v) => 3
        Err(e) if e == 7 => 4
        Err(e) => e
    }
}
fn main() -> I32 {
    if route(950, true) != 1 { return 1 }
    if route(950, false) != 2 { return 2 }
    if route(500, true) != 2 { return 3 }
    if route(5, true) != 3 { return 4 }
    if route(0, false) != 3 { return 5 }
    return 0
}
`

var m75GuardRejections = []struct {
	name, source, want string
}{
	{
		"guard-view-arm",
		"fn f(t: Table(U64), id: U64.Id) -> U64 {\n    return match t.get(id) {\n        Some(v) if v.n > 1 => 1\n        None => 2\n    }\n}\nfn main() -> I32 { return 0 }\n",
		"table-view match arm cannot carry a guard",
	},
	{
		"guard-not-exhaustive",
		"fn f(o: Option(U64), p: Bool) -> U64 {\n    return match o {\n        Some(v) if p => 1\n    }\n}\nfn main() -> I32 { return 0 }\n",
		"match is not exhaustive",
	},
	{
		"guard-consumes-binding",
		"type Res { n: U64 }\nimpl Cleanup for Res {\n    fn cleanup(take self) -> Unit { return }\n}\nfn drain_ok(take v: Res) -> Bool {\n    using held = v\n    return true\n}\nfn f(o: Option(Res)) -> U64 {\n    return match o {\n        Some(v) if drain_ok(v) => 1\n        _ => 2\n    }\n}\nfn main() -> I32 { return 0 }\n",
		"match guard only borrows",
	},
}

func TestM75GuardProductionQualification(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	object, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	files := map[string]string{"m75-guards.al": m75GuardProgram}
	mirText := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "m75-guards.al")
	if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
		t.Fatalf("guard MIR result: %+v stderr=%s", mirText, mirText.stderr)
	}
	repeat := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "m75-guards.al")
	if repeat != mirText {
		t.Fatal("guard MIR changed across processes")
	}
	cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", "m75-guards.al")
	if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
		t.Fatalf("guard C result: %+v stderr=%s", cResult, cResult.stderr)
	}
	assertPublicMIR(t, "m75-guards.al", mirText.stdout)
	if strings.Contains(cResult.stdout, "__s0_") {
		t.Fatal("guard generated C exposes bootstrap names")
	}
	compileAndRunProductionArtifact(t, cc, root, runtimeObject, cResult.stdout, 0)

	for _, rejection := range m75GuardRejections {
		rejection := rejection
		t.Run("reject-"+rejection.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{"reject.al": rejection.source}
			result := runProductionCompiler(t, exe, files, "check", "reject.al")
			if result.status == 0 || !strings.Contains(result.stderr, rejection.want) {
				t.Fatalf("reject %s: status=%d stderr=%q", rejection.name, result.status, result.stderr)
			}
		})
	}
	_ = object
}
