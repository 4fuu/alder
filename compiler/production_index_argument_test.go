// M8 index-projection mut arguments: a `mut` argument that names an element
// passes that element's storage. Array elements borrow directly; vector
// elements go through the existing mutable view of the vector, so no new view
// kind is involved. Field and index levels compose, and both the receiver
// position and a forwarded constrained cursor exercise the same gate.

const m8IndexArgumentPrelude = `trait Cursor {
    fn step(mut self) -> U64
}

type Cell {
    value: U64
}

impl Cursor for Cell {
    fn step(mut self) -> U64 {
        self.value = self.value + 1
        return self.value
    }
}

type Grid {
    rows: Vec(Cell)
    cells: Array(Cell, 2)
}

fn bump(C: type(Cursor), mut c: C) -> Unit {
    c.step()
    return
}
`

const m8IndexArgumentProgram = m8IndexArgumentPrelude + `
fn main() -> I32 {
    var grid = Grid(rows: Vec.new(Cell), cells: [Cell(value: 0), Cell(value: 0)])
    grid.rows.push(Cell(value: 10))
    grid.rows.push(Cell(value: 20))
    if grid.rows[0].step() != 11 { return 1 }
    bump(grid.rows[1])
    if grid.rows[1].value != 21 { return 2 }
    bump(grid.cells[0])
    if grid.cells[0].value != 1 { return 3 }
    var i: U64 = 1
    bump(grid.rows[i])
    if grid.rows[1].value != 22 { return 4 }
    var row: Array(Cell, 2) = [Cell(value: 0), Cell(value: 0)]
    bump(row[1])
    if row[1].value != 1 { return 5 }
    var items = Vec.new(Cell)
    items.push(Cell(value: 5))
    bump(items[0])
    if items[0].value != 6 { return 6 }
    return 0
}
`

var m8IndexArgumentRejections = []struct {
	name, source, want string
}{
	{
		// A let-bound array is not a mutable place.
		"immutable-root-index",
		m8IndexArgumentPrelude + `
fn main() -> I32 {
    let cells: Array(Cell, 2) = [Cell(value: 0), Cell(value: 0)]
    bump(cells[0])
    return 0
}
`,
		"mut cursor argument must be a mutable place",
	},
	{
		// A live view of the root excludes the exclusive borrow of an element.
		"live-view-of-root",
		m8IndexArgumentPrelude + `
fn main() -> I32 {
    var grid = Grid(rows: Vec.new(Cell), cells: [Cell(value: 0), Cell(value: 0)])
    grid.rows.push(Cell(value: 1))
    let view = grid.rows.slice(0, 1)
    bump(grid.cells[0])
    if view.len() != 1 { return 1 }
    return 0
}
`,
		"argument does not provide the parameter's required exclusive or owning access",
	},
	{
		// An element of a call result is not a place at all.
		"temporary-index",
		m8IndexArgumentPrelude + `
fn build() -> Array(Cell, 2) {
    return [Cell(value: 0), Cell(value: 0)]
}
fn main() -> I32 {
    bump(build()[0])
    return 0
}
`,
		"mut cursor argument must be a mutable place",
	},
}

func TestM8IndexArgumentQualification(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	t.Run("index-paths", func(t *testing.T) {
		t.Parallel()
		files := map[string]string{"index-argument.al": m8IndexArgumentProgram}
		mirText := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "index-argument.al")
		if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
			t.Fatalf("MIR result: %+v stderr=%s", mirText, mirText.stderr)
		}
		if !strings.Contains(mirText.stdout, "array.index.checked") || !strings.Contains(mirText.stdout, "vec.as_mut_slice") || !strings.Contains(mirText.stdout, "borrow_mut deref") {
			t.Fatalf("MIR passes elements by value instead of borrowing them:\n%s", mirText.stdout)
		}
		cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", "index-argument.al")
		if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
			t.Fatalf("C result: %+v stderr=%s", cResult, cResult.stderr)
		}
		compileAndRunProductionArtifact(t, cc, root, runtimeObject, cResult.stdout, 0)
	})

	for _, rejection := range m8IndexArgumentRejections {
		rejection := rejection
		t.Run("reject-"+rejection.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{"reject.al": rejection.source}
			result := runProductionCompiler(t, exe, files, "check", "reject.al")
			if result.status == 0 || !strings.Contains(result.stderr, rejection.want) {
				t.Fatalf("reject %s: status=%d stderr=%q", rejection.name, result.status, result.stderr)
			}
		})
	}
}
