// `else if` is an else whose block holds one nested if statement, so a chain
// keeps the ordinary block and statement rules. The program covers a
// multi-line chain, a single-line chain, and a chain inside a loop body.
const elseIfChainProgram = `fn classify(x: U64) -> U64 {
    if x == 0 {
        return 10
    } else if x == 1 {
        return 11
    } else if x == 2 {
        return 12
    } else {
        return 13
    }
}
fn bucket(x: U64) -> U64 {
    if x < 10 { return 1 } else if x < 20 { return 2 } else if x < 30 { return 3 } else { return 4 }
}
fn sum(n: U64) -> U64 {
    var total: U64 = 0
    var i: U64 = 0
    while i < n {
        if i == 0 {
            total = total + 1
        } else if i == 1 {
            total = total + 2
        } else {
            total = total + 3
        }
        i = i + 1
    }
    return total
}
fn main() -> I32 {
    if classify(0) != 10 { return 1 }
    if classify(1) != 11 { return 2 }
    if classify(2) != 12 { return 3 }
    if classify(9) != 13 { return 4 }
    if bucket(5) != 1 { return 5 }
    if bucket(15) != 2 { return 6 }
    if bucket(25) != 3 { return 7 }
    if bucket(35) != 4 { return 8 }
    if sum(4) != 9 { return 9 }
    return 0
}
`

func TestM75ElseIfQualification(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	files := map[string]string{"else-if-chains.al": elseIfChainProgram}
	mirText := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "else-if-chains.al")
	if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
		t.Fatalf("else-if MIR result: %+v stderr=%s", mirText, mirText.stderr)
	}
	repeat := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "else-if-chains.al")
	if repeat != mirText {
		t.Fatalf("else-if MIR changed across processes")
	}
	cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", "else-if-chains.al")
	if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
		t.Fatalf("else-if C result: %+v stderr=%s", cResult, cResult.stderr)
	}
	compileAndRunProductionArtifact(t, cc, root, runtimeObject, cResult.stdout, 0)
}
