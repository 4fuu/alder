// M8 conditional implementation constraints: a generic implementation
// satisfies a constraint when its head unifies with the concrete implementing
// type and its own constraints hold for the arguments that unification binds.
// A type parameter answers from its own declared constraints, so a generic
// body can forward a conditional value to another constrained call. The
// rejections keep every unsatisfied link in that chain a diagnostic.

const m8ConditionalConstraintProgram = `trait Valued {
    fn value(self) -> U64
}

type Leaf {
    n: U64
}

impl Valued for Leaf {
    fn value(self) -> U64 {
        return self.n
    }
}

type Box2(T: type) {
    v: T
}

impl(T: type(Valued)) Valued for Box2(T) {
    fn value(self) -> U64 {
        return self.v.value()
    }
}

fn take_val(T: type(Valued), v: T) -> U64 {
    return v.value()
}

fn outer(T: type(Valued), b: Box2(T)) -> U64 {
    return take_val(b)
}

fn main() -> I32 {
    let b = Box2(v: Leaf(n: 5))
    if b.value() != 5 { return 1 }
    let leaf = Leaf(n: 7)
    if take_val(leaf) != 7 { return 2 }
    if take_val(b) != 5 { return 3 }
    let mid = Box2(v: Leaf(n: 9))
    if outer(mid) != 9 { return 4 }
    if take_val(Box2(Leaf), b) != 5 { return 5 }
    return 0
}
`

var m8ConditionalConstraintRejections = []struct {
	name, source, want string
}{
	{
		// The argument type has no implementation at all.
		"no-implementation",
		`trait Valued {
    fn value(self) -> U64
}
type Leaf {
    n: U64
}
impl Valued for Leaf {
    fn value(self) -> U64 {
        return self.n
    }
}
type Box2(T: type) {
    v: T
}
impl(T: type(Valued)) Valued for Box2(T) {
    fn value(self) -> U64 {
        return self.v.value()
    }
}
fn take_val(T: type(Valued), v: T) -> U64 {
    return v.value()
}
fn main() -> I32 {
    let bad = take_val(5)
    return 0
}
`,
		"type does not implement a trait required here",
	},
	{
		// The conditional implementation's own constraint fails for the
		// argument that unification binds.
		"impl-constraint-unsatisfied",
		`trait Valued {
    fn value(self) -> U64
}
type Leaf {
    n: U64
}
impl Valued for Leaf {
    fn value(self) -> U64 {
        return self.n
    }
}
type Box2(T: type) {
    v: T
}
impl(T: type(Valued)) Valued for Box2(T) {
    fn value(self) -> U64 {
        return self.v.value()
    }
}
fn take_val(T: type(Valued), v: T) -> U64 {
    return v.value()
}
fn main() -> I32 {
    let bad = Box2(v: 5)
    let n = take_val(bad)
    return 0
}
`,
		"type does not implement a trait required here",
	},
}

func TestM8ConditionalConstraintQualification(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	t.Run("conditional-impl-satisfies", func(t *testing.T) {
		t.Parallel()
		files := map[string]string{"constraint-conditional.al": m8ConditionalConstraintProgram}
		mirText := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "constraint-conditional.al")
		if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
			t.Fatalf("MIR result: %+v stderr=%s", mirText, mirText.stderr)
		}
		cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", "constraint-conditional.al")
		if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
			t.Fatalf("C result: %+v stderr=%s", cResult, cResult.stderr)
		}
		compileAndRunProductionArtifact(t, cc, root, runtimeObject, cResult.stdout, 0)
	})

	for _, rejection := range m8ConditionalConstraintRejections {
		rejection := rejection
		t.Run("reject-"+rejection.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{"reject.al": rejection.source}
			result := runProductionCompiler(t, exe, files, "check", "reject.al")
			if result.status == 0 || !strings.Contains(result.stderr, rejection.want) {
				t.Fatalf("reject %s: status=%d stderr=%q", rejection.name, result.status, result.stderr)
			}
		})
	}
}
