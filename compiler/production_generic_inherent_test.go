// M8 generic inherent implementations: `impl(T: type(...)) Type(T) { ... }`
// declares methods and associated functions owned by an applied generic type.
// Methods are instance-only like methods of a generic trait implementation;
// the receiver binds the implementation parameters for a method call, and the
// argument and expected-result types bind them for an associated function.
// The rejection set keeps each broken head a numbered, messaged diagnostic.

const m8GenericInherentProgram = `trait Reader {
    fn label(self) -> U64
}

type Source {
    value: U64
}

impl Reader for Source {
    fn label(self) -> U64 {
        return self.value
    }
}

type BufReader(T: type(Reader)) {
    source: T
}

impl(T: type(Reader)) BufReader(T) {
    fn new(source: T) -> BufReader(T) {
        return BufReader(T)(source: source)
    }

    fn label(self) -> U64 {
        return self.source.label()
    }

    fn inner(self) -> T {
        return self.source
    }
}

impl(T: type(Reader)) Reader for BufReader(T) {
    fn label(self) -> U64 {
        return self.source.label()
    }
}

fn read_one(R: type(Reader), reader: R) -> U64 {
    return reader.label()
}

fn main() -> I32 {
    let s = Source(value: 7)
    let b = BufReader.new(s)
    if b.label() != 7 { return 1 }
    if read_one(b) != 7 { return 2 }
    let c = b.inner()
    if c.value != 7 { return 3 }
    return 0
}
`

type m8GenericInherentRejection struct {
	name   string
	source string
	want   string
}

var m8GenericInherentRejections = []m8GenericInherentRejection{
	{
		name: "parameter-not-in-owner",
		source: `type Boxed(T: type, U: type) {
    left: T
    right: U
}

impl(T: type, U: type, V: type) Boxed(T, U) {
    fn tag(self) -> U64 {
        return 0
    }
}

fn main() -> I32 {
    return 0
}
`,
		want: "implementation parameter \"V\" does not appear in the implementing type",
	},
	{
		name: "bare-parameter-owner",
		source: `trait Valued {
    fn value(self) -> U64
}

impl(T: type(Valued)) T {
    fn tag(self) -> U64 {
        return 0
    }
}

fn main() -> I32 {
    return 0
}
`,
		want: "an implementation cannot target a bare type parameter",
	},
	{
		name: "missing-restated-constraint",
		source: `trait Valued {
    fn value(self) -> U64
}

type Boxed(T: type(Valued)) {
    v: T
}

impl(T: type) Boxed(T) {
    fn tag(self) -> U64 {
        return 0
    }
}

fn main() -> I32 {
    return 0
}
`,
		want: "implementations must restate every constraint the implementing type declares",
	},
	{
		name: "unbound-implementation-parameter",
		source: `type Boxed(T: type) {
    v: T
}

impl(T: type) Boxed(T) {
    fn tag() -> U64 {
        return 0
    }
}

fn main() -> I32 {
    if Boxed.tag() != 0 { return 1 }
    return 0
}
`,
		want: "type argument inference failed",
	},
}

func TestM8GenericInherentImpls(t *testing.T) {
	if os.Getenv("UPDATE_GOLDEN") == "" {
		t.Parallel()
	}
	cc, err := exec.LookPath("gcc")
	if err != nil {
		t.Skip("gcc not available")
	}
	root, err := filepath.Abs("..")
	if err != nil {
		t.Fatal(err)
	}
	_, exe, _ := getSharedProductionBuild(t, cc, root)
	runtimeObject := buildRuntimeObject(t, cc, root)

	t.Run("generic-inherent-accepted", func(t *testing.T) {
		t.Parallel()
		files := map[string]string{"generic-inherent.al": m8GenericInherentProgram}
		mirText := runProductionCompiler(t, exe, files, "compile", "--emit=mir", "generic-inherent.al")
		if mirText.status != 0 || mirText.stderr != "" || !strings.HasPrefix(mirText.stdout, "mir 6\n") {
			t.Fatalf("MIR result: %+v stderr=%s", mirText, mirText.stderr)
		}
		assertPublicMIR(t, "generic-inherent", mirText.stdout)
		cResult := runProductionCompiler(t, exe, files, "compile", "--emit=c", "generic-inherent.al")
		if cResult.status != 0 || cResult.stderr != "" || !strings.HasPrefix(cResult.stdout, "/* Generated by the Alder C11 backend.") {
			t.Fatalf("C result: %+v stderr=%s", cResult, cResult.stderr)
		}
		compileAndRunProductionArtifact(t, cc, root, runtimeObject, cResult.stdout, 0)
	})

	for _, rejection := range m8GenericInherentRejections {
		rejection := rejection
		t.Run("reject-"+rejection.name, func(t *testing.T) {
			t.Parallel()
			files := map[string]string{"reject.al": rejection.source}
			result := runProductionCompiler(t, exe, files, "check", "reject.al")
			if result.status == 0 || !strings.Contains(result.stderr, rejection.want) {
				t.Fatalf("reject %s: status=%d stderr=%q", rejection.name, result.status, result.stderr)
			}
		})
	}
}
